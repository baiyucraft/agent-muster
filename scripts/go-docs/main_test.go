func TestChangedDeclarations(t *testing.T) {
	const baseline = "package example\n\nfunc Read() int { return 1 }\n"
	for _, testcase := range []struct {
		name, source, want string
	}{
		{"body edit", "package example\n\nfunc Read() int { return 2 }\n", ""},
		{"signature edit", "package example\n\nfunc Read(name string) int { return 1 }\n", "缺少 Read"},
		{"new type", baseline + "type Cursor int\n", "缺少 Cursor"},
		{"grouped type", baseline + "type (\n// Cursor 保存最后事件编号。\nCursor int\n)\n", ""},
		{"method receiver", baseline + "type cursor int\nfunc (c *cursor) Next() {}\n", "缺少 Next"},
		{"wrong prefix", "package example\n// ReadNext 读取值。\nfunc Read() {}\n", "以 Read 开头"},
		{"english comment", "package example\n// Read returns a value.\nfunc Read() {}\n", "默认使用中文"},
		{"contract comment", "package example\n// Read 读取值。\nfunc Read() {}\n", ""},
		{"generated", "// Code generated by fixture. DO NOT EDIT.\npackage example\nfunc Read() {}\n", ""},
	} {
		t.Run(testcase.name, func(t *testing.T) {
			err := checkFile("example.go", []byte(baseline), []byte(testcase.source))
			if testcase.want == "" && err != nil || testcase.want != "" && (err == nil || !strings.Contains(err.Error(), testcase.want)) {
				t.Fatalf("got %v, want %q", err, testcase.want)
			}
		})
	}
}

func TestRemovingDocs(t *testing.T) {
	before := []byte("// Package example 提供测试入口。\npackage example\n// Cursor 保存事件编号。\ntype Cursor int\n")
	after := []byte("package example\ntype Cursor int\n")
	err := checkFile("example.go", before, after)
	if err == nil || !strings.Contains(err.Error(), "缺少 Cursor") || !strings.Contains(err.Error(), "缺少 Package example") {
		t.Fatalf("expected errors for removed documentation, got %v", err)
	}
}

func TestGitCandidates(t *testing.T) {
	t.Chdir(t.TempDir())
	command := func(args ...string) {
		t.Helper()
		if _, err := git("", args...); err != nil {
			t.Fatal(err)
		}
	}
	write := func(name, source string) {
		t.Helper()
		if err := os.WriteFile(name, []byte(source), 0600); err != nil {
			t.Fatal(err)
		}
	}
	command("init", "--quiet")
	command("config", "user.name", "Go docs test")
	command("config", "user.email", "go-docs@example.invalid")
	command("config", "commit.gpgsign", "false")
	command("config", "core.hooksPath", "disabled-hooks")
	write("测试.go", "package example\nfunc Read() int { return 1 }\n")
	if err := run(io.Discard, nil); err == nil || !strings.Contains(err.Error(), "缺少 Read") {
		t.Fatalf("initial working tree: %v", err)
	}
	command("add", "--", "测试.go")
	if err := run(io.Discard, []string{"--staged"}); err == nil || !strings.Contains(err.Error(), "缺少 Read") {
		t.Fatalf("initial index: %v", err)
	}
	command("commit", "--quiet", "-m", "测试基线")
	write("测试.go", "package example\nfunc Read(name string) int { return 1 }\n")
	command("add", "--", "测试.go")
	write("测试.go", "package example\n// Read 按名称读取值。\nfunc Read(name string) int { return 1 }\n")
	if err := run(io.Discard, []string{"--staged", "--", "测试.go"}); err == nil || !strings.Contains(err.Error(), "缺少 Read") {
		t.Fatalf("partially staged index: %v", err)
	}
	if err := run(io.Discard, nil); err != nil {
		t.Fatalf("corrected working tree: %v", err)
	}
	command("commit", "--quiet", "-m", "提交缺少注释的签名")
	if err := run(io.Discard, []string{"--base", "HEAD^", "--ref", "HEAD"}); err == nil || !strings.Contains(err.Error(), "缺少 Read") {
		t.Fatalf("committed candidate: %v", err)
	}
}
